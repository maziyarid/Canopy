function row(
  partial: Omit<KeywordRow, "opportunity" | "id"> & { id?: string },
): KeywordRow {
  const opportunity = opportunityScore(partial.volume, partial.kd, partial.ppc);
  return { id: partial.id ?? partial.keywordId, opportunity, ...partial };
}

